"""
================================================================================
ТЕСТ-ПЛАН: ВХОД В СИСТЕМУ / USER LOGIN
================================================================================

ОПИСАНИЕ
--------
Данный модуль содержит автотесты для проверки функциональности входа в систему
зарегистрированных пользователей.

ОСНОВАН НА ТРЕБОВАНИЯХ
----------------------
Документ: ID2 Вход в систему / User Login

КРИТЕРИИ ПРИЕМКИ
----------------
1. Пользователь должен ввести логин и пароль для входа
2. После успешного входа пользователь перенаправляется на главную страницу

ИСКЛЮЧИТЕЛЬНЫЕ СЛУЧАИ
---------------------
1. Невалидные данные → сообщение об ошибке валидации
2. Неверный логин или пароль → сообщение: "Неверное имя пользователя или пароль"

СТРУКТУРА ТЕСТОВ
----------------
1. Позитивные тесты (test_auth_pos)
   - Успешный вход с валидными данными
   - Проверка редиректа на главную страницу

2. Негативные тесты (test_auth_neg)
   - Пустые поля
   - Неверный логин
   - Неверный пароль
   - Логин короче 3 символов
   - Пароль короче 8 символов


ЗАПУСК ТЕСТОВ
-------------
pytest test_auth_pos.py -v        # Запуск позитивных тестов
pytest test_auth_neg.py -v        # Запуск негативных тестов
pytest test_auth_*.py -v          # Запуск всех тестов

================================================================================
"""